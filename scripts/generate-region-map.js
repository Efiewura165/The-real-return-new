const fs = require("fs");
const path = require("path");

const svg = fs.readFileSync(path.join(__dirname, "../public/images/map/ghana-regions.svg"), "utf-8");

const REGION_META = {
  Greater_Accra_Region: { label: "Greater Accra", targets: ["Greater Accra"] },
  "Eastern_Region_(Ghana)": { label: "Eastern Region", targets: ["Eastern Region"] },
  Ashanti_Region: { label: "Ashanti Region", targets: ["Ashanti Region"] },
  "Central_Region_(Ghana)": { label: "Central Region", targets: ["Central Region"] },
  "Western_Region_(Ghana)": { label: "Western Region", targets: ["Western Region"] },
  "Brong-Ahafo_Region": { label: "Bono East", targets: ["Bono East Region"] },
  Volta_Region: { label: "Volta Region", targets: ["Volta Region"] },
  "Northern_Region_(Ghana)": { label: "Savannah & Northern Region", targets: ["Savannah Region", "Northern Region"] },
  Upper_West_Region: { label: "Upper West", targets: [] },
  Upper_East_Region: { label: "Upper East", targets: [] },
};

const blockRe = /<a\s+id="([^"]+)"\s+xlink:href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/g;
const regions = [];
let m;
while ((m = blockRe.exec(svg)) !== null) {
  const [, , href, inner] = m;
  const key = decodeURIComponent(href).split("/wiki/")[1];
  const pathMatch = inner.match(/<path[^>]*\bd="([^"]+)"/);
  const meta = REGION_META[key];
  if (!meta) throw new Error("Unmapped region: " + key);
  regions.push({ key, label: meta.label, targets: meta.targets, d: pathMatch[1] });
}

// Background decorative paths (not wrapped in <a>): Lake Volta fill + a small boundary line.
const bgPaths = [];
const usedIds = new Set();
blockRe.lastIndex = 0;
while ((m = blockRe.exec(svg)) !== null) {
  const idMatch = m[3].match(/<path[^>]*\bid="([^"]+)"/);
  if (idMatch) usedIds.add(idMatch[1]);
}
const allPathRe = /<path\b[^>]*\bid="([^"]+)"[^>]*\/?>(?:<\/path>)?/g;
while ((m = allPathRe.exec(svg)) !== null) {
  if (usedIds.has(m[1])) continue;
  const dMatch = m[0].match(/\bd="([^"]+)"/);
  const fillMatch = m[0].match(/fill:#([0-9a-fA-F]{6})/);
  if (dMatch) bgPaths.push({ d: dMatch[1], fill: fillMatch ? `#${fillMatch[1]}` : "none" });
}

const output = `// Generated by scripts/generate-region-map.js from Wikimedia Commons
// "Clickable Regions of Ghana.svg" (GFDL / CC BY-SA 3.0) -- do not hand-edit path data.
export interface GhanaMapRegion {
  key: string;
  label: string;
  /** Names in REGION_ORDER (content/experiences) this map shape links to. Empty = no packages yet. */
  targets: string[];
  d: string;
}

export const GHANA_MAP_VIEWBOX = "0 0 1075 1500";

export const GHANA_MAP_BACKGROUND_PATHS: { d: string; fill: string }[] = ${JSON.stringify(bgPaths, null, 2)};

export const GHANA_MAP_REGIONS: GhanaMapRegion[] = ${JSON.stringify(regions, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, "../lib/ghana-map-data.ts"), output);
console.log("Wrote lib/ghana-map-data.ts with", regions.length, "regions and", bgPaths.length, "background paths");
